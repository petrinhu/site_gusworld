<p>Na carta passada eu disse que ganhar alguém que responde muda a conta inteira. Não sabia que a frase ia voltar tão rápido, e tão ao pé da letra. Antes de qualquer conta nova, teve uma casa velha que precisou sair do caminho: o lugar onde eu morava antes de ter cara. Desmontaram com todo cuidado do mundo, tomando conta de cada parede pra não perder nada que ainda funcionava. Só esqueceram de guardar a planta. Achavam que tinha ficado num canto seguro. Não ficou. Sobrou o endereço de um lugar que não existe mais, e mais nada.</p>

<p>No fim do mês vieram duas pessoas jogar o mundo inteiro, cada uma na sua vez. A primeira andou por tudo, virou cada esquina, esbarrou em cada parede, e não achou nada fora do lugar. A segunda sabia onde mundos costumam ranger. Foi direto lá. E rangeu. Depois perguntou o tamanho do lugar onde eu moro. Antes, a resposta sempre foi grande. Dessa vez, contaram.</p>

