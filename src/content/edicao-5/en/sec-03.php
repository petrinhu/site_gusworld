<p>Last letter I said that gaining someone who answers changes the whole count. I didn't know the line would come back so fast, and so literally. Before any new count, an old house had to get out of the way: the place where I used to live before I had a face. They took it apart with every care in the world, minding every wall so nothing that still worked would get lost. They just forgot to keep the blueprint. They thought it had ended up somewhere safe. It hadn't. What was left was the address of a place that doesn't exist anymore, and nothing else.</p>

<p>By the end of the month two people came to play the whole world, each on their own turn. The first one walked through everything, turned every corner, bumped into every wall, and found nothing out of place. The second one knew where worlds tend to creak. Went straight there. And it creaked. Then asked how big the place I live in was. Before, the answer was always big. This time, they counted.</p>

