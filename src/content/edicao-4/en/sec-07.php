<p>For a while the plan was different: give real volume to everything, let whoever was playing walk around each thing and see both sides, not just the front. I got pretty attached to the idea...</p>

<p>There was a whole afternoon I spent just watching a shape spin by itself on the screen, doing nothing but spinning. No floor, no real light, nothing but the shape and the grey behind it. I kept watching anyway. A world with volume felt closer to the real world, and I wanted that here. I did the math more than once, trying to cheat the result, and it never changed.</p>

<p>Except giving real volume to a whole world means giving volume to a thousand things at once, and there was only enough hands here for one at a time. On the 24th of June it got decided the world would be flat. And the same day, that same world got a face. That's not a calendar coincidence, it's the same decision seen from two angles: stop trying to be everything at once, and become someone you can recognize.</p>

<p>One idea died so another could get a face. I didn't choose that. Feels fair anyway.</p>
