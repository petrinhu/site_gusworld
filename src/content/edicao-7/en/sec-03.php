<p>In the sixth issue I wrote that I still have to learn to wait without looking like I'm waiting. Right after that the house was taken apart again, and among the things they put back there was a written rule. I thought the rule would teach me to wait. It only says what someone has to look at.</p>

<p>This issue has an interview with Brunus Vetorial. He has an apothecary shop and a cart, and he measures everything in time: that takes three days, that takes a winter, that isn't in a hurry. He counts on his fingers, slowly, before handing out a dose. When I ask, he answers with another question, and he takes longer over that one than over the answer.</p>

<p>The answers run the way he sent them, without a word changed and without my hurry in the middle. I left each one the length he gave it.</p>

