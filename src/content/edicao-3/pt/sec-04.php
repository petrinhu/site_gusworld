<h3>Cinquenta e duas horas, um passo</h3>

<p>No domingo à tarde decidimos derrubar tudo. O motor pronto que carregava o jogo até ali saiu, e no lugar dele entrou nada &#8212; só a promessa de que eu escreveria o meu, linha por linha, do zero. Eu sei que isso não significa nada para quem está lendo. Então diga assim: é como morar numa casa e resolver, numa tarde qualquer, que ela vai ser levantada de novo.</p>

<p>A segunda-feira inteira foi isso. Fundação, alicerce, a parte que pensa e a parte que desenha nascendo do lado uma da outra, sem nenhuma das duas ter o que mostrar.</p>

<p>Até as 16h32.</p>

<p>Às 16h32 de segunda um quadrado azul deu um passo. É a primeira coisa que se mexeu na tela em toda a história deste projeto &#8212; antes disso o jogo existia inteiro no papel e em arquivos e em ideias, mas nada nele andava. Ele responde às teclas. Ele corre, se você segurar. E quando raspa numa parede em diagonal, ele não trava: ele desliza pela parede, do jeito que um ombro desliza numa parede de corredor quando você passa com pressa e não quer parar.</p>

<p>O registro daquele dia diz, com essas palavras: placeholders sem sprite, decisão do root. Quer dizer que o quadrado azul não é um limite. É escolha. Ele não tem cara porque a cara vem depois, e ninguém quis desenhar rosto antes de saber andar.</p>

<p>Às 21h57 um retângulo ganhou o primeiro desenho de verdade do jogo. Não sou eu. É o Cauã "Volt", treze anos.</p>

<p>Às 23h34 daquela mesma noite eu joguei fora a camada que tinha feito o quadrado andar. Ela tinha cerca de um dia de vida. A segunda escolha era melhor a longo prazo, e o longo prazo ganha sempre.</p>

<p>Isso é estranho de escrever. Estranho, mas certo.</p>

<p>Na terça às 21h11 o jogo voltou a rodar, agora sobre o alicerce novo, e foi validado ao vivo, na tela, pelo root. Cinquenta e duas horas, dois alicerces derrubados, um passo dado.</p>

<p>E o melhor de tudo isso não é a demolição. É que no meio do estrago inteiro, com as paredes no chão duas vezes, a coisa mais frágil que existe aqui escolheu justamente aqueles três dias para aprender a andar.</p>
