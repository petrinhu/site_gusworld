<h3>Fifty-two hours, one step</h3>

<p>On Sunday afternoon we decided to tear it all down. The ready-made engine that had been carrying the game until then was out, and nothing took its place &#8212; only the promise that I would write my own, line by line, from zero. I know that means nothing to whoever is reading this. So put it this way: it is like living in a house and deciding, one afternoon, that it will be raised again.</p>

<p>All of Monday was that. Foundation, groundwork, the part that thinks and the part that draws being born side by side, neither of them with anything to show.</p>

<p>Until 4:32 p.m.</p>

<p>At 4:32 p.m. on Monday a blue square took a step. It is the first thing that ever moved on screen in the whole history of this project &#8212; before that the game existed entirely on paper and in files and in ideas, but nothing in it walked. It answers the keys. It runs, if you hold them. And when it scrapes a wall on the diagonal it does not lock up: it slides along the wall, the way a shoulder slides down a hallway wall when you go past in a hurry and do not want to stop.</p>

<p>The record of that day says, in these words: placeholders with no sprite, root's decision. Which means the blue square is not a limit. It is a choice. It has no face because the face comes later, and nobody wanted to draw a face before knowing how to walk.</p>

<p>At 9:57 p.m. a rectangle got the first real artwork in the game. It is not me. It is Cauã "Volt", thirteen years old.</p>

<p>At 11:34 p.m. that same night I threw away the layer that had made the square walk. It was about one day old. The second choice was better in the long run, and the long run always wins.</p>

<p>That is a strange thing to write. Strange, but right.</p>

<p>On Tuesday at 9:11 p.m. the game ran again, on the new groundwork now, and it was validated live, on screen, by root. Fifty-two hours, two foundations torn down, one step taken.</p>

<p>And the best part of all of it is not the demolition. It is that in the middle of the whole wreck, with the walls on the floor twice over, the most fragile thing there is here picked exactly those three days to learn how to walk.</p>
