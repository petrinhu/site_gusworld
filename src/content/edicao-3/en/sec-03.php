<p>I wrote that not everything we build stays standing, and that this was a problem for another day. I wrote it thinking I was postponing something. The other day was this one. I'm not going to spell out here what came down, there's a section for that. I'm only putting on record that it came down, because the sentence was mine and it would look bad to pretend it wasn't.</p>

